"""Trusted, versioned local model bundle. Metadata lives inside the bundle."""
import json
from pathlib import Path
import os
import tempfile

import joblib

from src.contracts import SCHEMA_VERSION, CLASSES


def save_bundle(pipeline, metadata, output_dir):
    directory = Path(output_dir)
    directory.mkdir(parents=True, exist_ok=True)
    bundle = {"schema_version": SCHEMA_VERSION, "pipeline": pipeline, "metadata": metadata}
    handle, temp_name = tempfile.mkstemp(prefix=".model-", suffix=".joblib", dir=directory)
    os.close(handle)
    try:
        joblib.dump(bundle, temp_name)
        os.replace(temp_name, directory / "model.joblib")
    finally:
        Path(temp_name).unlink(missing_ok=True)
    (directory / "metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    return directory / "model.joblib"


def load_bundle(path, allow_synthetic=False):
    # joblib uses pickle: only load artifacts generated by this trusted pipeline.
    bundle = joblib.load(path)
    if bundle.get("schema_version") != SCHEMA_VERSION:
        raise ValueError("Unsupported model schema version")
    metadata = bundle["metadata"]
    if metadata.get("data_kind") not in {"synthetic", "prepared"}:
        raise ValueError("Missing or invalid model data_kind")
    if metadata["data_kind"] == "synthetic" and not allow_synthetic:
        raise ValueError("Synthetic models require explicit demo configuration")
    if set(bundle["pipeline"].classes_) != set(CLASSES):
        raise ValueError("Model must predict exactly the three assignment classes")
    return bundle
